-- 由 conf/forward.lua 生成 conf/stream.d/forward.conf
-- 用法: luajit bin/gen-conf.lua <project_root>
local root = arg[1] or "."
local file = root .. "/conf/forward.lua"

local chunk, err = loadfile(file)
if not chunk then
    io.stderr:write("加载配置失败 " .. file .. ": " .. tostring(err) .. "\n")
    os.exit(1)
end
local ok, rules = pcall(chunk)
if not ok then
    io.stderr:write("执行配置失败 " .. file .. ": " .. tostring(rules) .. "\n")
    os.exit(1)
end
if type(rules) ~= "table" then
    io.stderr:write("conf/forward.lua 必须返回 table\n")
    os.exit(1)
end

local out = { "# AUTO-GENERATED by bin/sync-conf.sh -- DO NOT EDIT",
              "# 源: conf/forward.lua" }

for _, r in ipairs(rules) do
    if type(r) ~= "table" or not r.name or not r.listen then
        io.stderr:write("规则缺少 name/listen: " .. tostring(r and r.name) .. "\n")
        os.exit(1)
    end
    if r.enabled ~= false then
        local proto = r.proto or "tcp"
        out[#out + 1] = ""
        out[#out + 1] = "# " .. r.name .. " (" .. proto .. ")"
        out[#out + 1] = "server {"
        if proto == "udp" then
            out[#out + 1] = "    listen " .. r.listen .. " udp;"
        else
            out[#out + 1] = "    listen " .. r.listen .. ";"
        end
        out[#out + 1] = "    content_by_lua_block { require(\"framework\").handle(\"" .. r.name .. "\") }"
        out[#out + 1] = "}"
    end
end
out[#out + 1] = ""

io.write(table.concat(out, "\n"))
